const assert = require('node:assert/strict');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const fs = require('node:fs');
const {chromium} = require(path.join(process.argv[2], 'playwright'));
(async()=>{
 const options = {headless:true};
 if(process.argv[3])options.executablePath=process.argv[3];
 const browser = await chromium.launch(options);
 const page = await browser.newPage({viewport:{width:1280,height:960}});
 const failures=[];
 page.on('pageerror', error=>failures.push(error.message));
 const file=path.resolve('examples/research-v3/visuals/logic-chain.html');
 await page.goto(pathToFileURL(file).href);
 assert.equal(await page.locator('#chain li').count(),6);
 assert.equal(await page.locator('#play').innerText(),'播放');
 assert.equal(await page.locator('#position').innerText(),'1 / 6');
 await page.locator('#next').click();
 assert.equal(await page.locator('#position').innerText(),'2 / 6');
 await page.locator('summary').first().click();
 assert.equal(await page.locator('details').first().getAttribute('open'),'');
 await page.locator('#play').click();
 assert.equal(await page.locator('#play').innerText(),'暂停');
 await page.waitForFunction(()=>document.querySelector('#position').textContent==='3 / 6',{},{timeout:10000});
 await page.locator('#play').click();
 assert.equal(await page.locator('#play').innerText(),'播放');
 fs.mkdirSync('tests/screenshots',{recursive:true});
 await page.screenshot({path:'tests/screenshots/logic-desktop.png',fullPage:true});
 await page.locator('#present').click();
 assert.equal(await page.locator('#present').getAttribute('aria-pressed'),'true');
 assert.ok(await page.locator('#claims').isVisible(),'Presentation must not hide evidence and boundaries.');
 await page.screenshot({path:'tests/screenshots/logic-presentation.png',fullPage:true});
 await page.keyboard.press('Escape');
 await page.setViewportSize({width:360,height:900});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.emulateMedia({reducedMotion:'reduce'});
 assert.equal(await page.locator('.node[aria-current=true] button').evaluate(el=>getComputedStyle(el).transform),'none');
 assert.ok((await page.locator('#motion-note').innerText()).includes('减少'));
 await page.screenshot({path:'tests/screenshots/logic-mobile.png',fullPage:true});
 await page.goto(pathToFileURL(path.resolve('examples/research-v3/report.html')).href);
 assert.ok(await page.locator('h1').innerText());
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.equal(await page.locator('#contents').getAttribute('open'),null);
 await page.locator('#contents summary').click();
 await page.locator('aside nav a').nth(1).click();
 await page.waitForFunction(()=>document.querySelector('aside nav a[aria-current="location"]')?.hash==='#section-2');
 await page.locator('#reader-focus').click();
 assert.ok(!await page.locator('aside').isVisible());
 await page.locator('#reader-type').click();
 assert.equal(await page.locator('.report-content').evaluate(el=>getComputedStyle(el).fontSize),'20px');
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.evaluate(()=>scrollTo(0,0));
 await page.screenshot({path:'tests/screenshots/report-mobile.png'});
 await page.locator('#reader-focus').click();await page.locator('#reader-type').click();
 await page.setViewportSize({width:1440,height:1000});
 await page.evaluate(()=>scrollTo(0,0));
 await page.screenshot({path:'tests/screenshots/report-desktop.png'});
 await page.emulateMedia({media:'print'});
 assert.ok(!await page.locator('aside').isVisible());
 assert.ok(await page.locator('.report-section').last().isVisible());
 await page.screenshot({path:'tests/screenshots/report-print.png'});
 const offline=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
 const fallback=await offline.newPage();await fallback.goto(pathToFileURL(path.resolve('examples/research-v3/report.html')).href);
 assert.ok(await fallback.locator('.report-section').count()>5);
 assert.ok(await fallback.locator('aside nav a').first().isVisible());
 assert.ok(!await fallback.locator('.reader-tools').isVisible());
 assert.ok(await fallback.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await offline.close();
 assert.deepEqual(failures,[]);
 await browser.close();
 console.log('BROWSER_OK: offline, stepping, presentation evidence, mobile, reduced-motion, report navigation/focus/type/print/no-JS fallback, no JS errors');
})().catch(error=>{console.error(error);process.exit(1)});
